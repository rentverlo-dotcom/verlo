
self.addEventListener("install", () => {
  self.skipWaiting()
})

self.addEventListener("activate", (event) => {
  event.waitUntil(self.clients.claim())
})

async function sendPushAck(
  deliveryId,
  stage
) {
  if (!deliveryId) {
    return
  }

  try {
    await fetch(
      "/api/push/ack",
      {
        method: "POST",

        headers: {
          "Content-Type":
            "application/json",
        },

        body:
          JSON.stringify({
            delivery_id:
              deliveryId,

            stage,
          }),
      }
    )
  } catch (error) {
    console.error(
      "Push ACK failed",
      {
        deliveryId,
        stage,
        error,
      }
    )
  }
}

self.addEventListener("push", (event) => {
  let data = {}

  try {
    data =
      event.data
        ? event.data.json()
        : {}
  } catch {
    data = {
      title:
        "Verlo",

      body:
        event.data
          ? event.data.text()
          : "",
    }
  }

  const title =
    data.title ||
    "Verlo"

  const deliveryId =
    data.delivery_id ||
    null

  const options = {
    body:
      data.body ||
      "",

    icon:
      "/logo-verlo.png",

    badge:
      "/logo-verlo.png",

    data: {
      url:
        data.url ||
        "/",

      delivery_id:
        deliveryId,

      lead_id:
        data.lead_id ||
        null,

      subscription_id:
        data.subscription_id ||
        null,
    },
  }

  event.waitUntil(
    (async () => {
      await self.registration
        .showNotification(
          title,
          options
        )

      await sendPushAck(
        deliveryId,
        "displayed"
      )
    })()
  )
})

self.addEventListener(
  "notificationclick",
  (event) => {
    event.waitUntil(
      (async () => {
        const deliveryId =
          event.notification?.data?.delivery_id ||
          null

        try {
          const rawUrl =
            event.notification?.data?.url ||
            "/"

          // Push URLs are generated by Verlo. Keep click destinations
          // on this origin so a stale or malformed payload cannot send
          // a user to another site.
          const destination =
            new URL(rawUrl, self.location.origin)

          if (destination.origin !== self.location.origin) {
            throw new Error("Invalid push destination")
          }

          // Let the browser open the push destination directly (including
          // an installed PWA). Reuse a tab only if that is unavailable.
          try {
            const opened =
              await clients.openWindow(destination.href)

            if (opened) {
              await opened.focus()
              event.notification.close()
              await sendPushAck(deliveryId, "clicked")
              return
            }
          } catch (error) {
            console.error("Push window opening failed", error)
          }

          const clientList =
            await clients.matchAll({
              type: "window",
              includeUncontrolled: true,
            })

          for (const client of clientList) {
            if (new URL(client.url).origin !== destination.origin) {
              continue
            }

            try {
              const navigated =
                await client.navigate(destination.href)

              if (navigated) {
                await navigated.focus()
                event.notification.close()
                await sendPushAck(deliveryId, "clicked")
                return
              }
            } catch (error) {
              console.error("Push client navigation failed", error)
            }
          }

          throw new Error("Could not open push destination")
        } catch (error) {
          console.error(
            "Push notification click failed",
            error
          )
        }
      })()
    )
  }
)
